
#include<iostream>
using namespace std;

// Node Class
class Node {
public:
    int data;
    Node* next;
};

int main() {
    Node* first = new Node();
    Node* second = new Node();
    Node* third = new Node();

    first->data = 10;
    second->data = 20;
    third->data = 30;

    first->next = second;
    second->next = third;
    third->next = NULL;

    cout<<first->data<<endl;
    cout<<first->next<<endl;

    return 0;
}
